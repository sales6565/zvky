/* Which folders a person may see, and which folder a project owns.
 *
 * ===========================================================================
 * THE MAPPING IS A SNAPSHOT, NOT A DERIVATION, and that is the whole design.
 *
 * The folder name is DERIVED from the project the first time the project needs
 * one, and then WRITTEN to projects.server_folder and never recomputed. So
 * renaming a project, or correcting its code, moves nothing and orphans
 * nothing: the folder on the office server keeps its name and the project keeps
 * pointing at it. A studio that wants the folder renamed renames it on the
 * server and edits the mapping, which is a deliberate two-step rather than a
 * side effect of editing a project's title.
 *
 * It is also editable, because the common case on day one is a share that
 * already has folders: "ALPHA 2024" exists with four months of work in it, and
 * the mapping is how the project is pointed at it instead of at a new empty
 * ALPHA.
 *
 * ===========================================================================
 * SCOPING. A non-admin sees the top-level folders of the projects
 * visibleProjects() returns, plus the shared folders, and nothing else — not
 * the root listing, not a sibling project, not a path they typed. Every token
 * is minted against one of these prefixes and the gateway enforces the prefix
 * again on its side, so a client path is checked twice and trusted never.
 *
 * server.browse_all (Super Admin by default) is the one exception and it is a
 * single prefix: '' — the root. It is not "skip the check"; it is a wider
 * prefix that goes through the same check.
 */
const crypto = require('node:crypto');
const permissions = require('./permissions');
const paths = require('./server-paths');
const serverSettings = require('./server-settings');

/* A folder name from a project. Letters, digits, spaces, dashes and
   underscores; everything else folded away, because this has to be a legal
   name on NTFS and on ext4 and readable by whoever opens the share in
   Explorer. */
function slug(text) {
  return String(text === undefined || text === null ? '' : text)
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 60)
    .replace(/[. ]+$/, '');
}

/* THE NAME FIRST, NOT THE CODE, and that is a correction to the obvious design.
 *
 * "Derive it from the project code" is what anybody would specify, and it is
 * wrong in THIS schema. projects.code is not a studio-assigned code: it is
 * generated by codeFor() in src/routes/projects.js as the INITIALS of the name
 * and re-derived on every rename. "Alpha" has the code "A". So a folder derived
 * from the code would be called A, "Alpha" and "Atlas" would both want it, and
 * the loser would be A-2 — a share full of single letters that nobody can read
 * and that says nothing about whose work is in it.
 *
 * The NAME is what a person would have typed on that folder, so it goes first.
 * The code is kept as the fallback for a project whose name slugs away to
 * nothing, and the id behind that so this function always answers.
 *
 * It costs nothing in stability: whatever this returns is snapshotted into
 * projects.server_folder the first time it is needed and never recomputed, so a
 * rename moves no folder either way — and the mapping is editable, which is how
 * a studio that wants ALPHA-24 gets ALPHA-24. */
function derive(project) {
  const fromName = slug(project && project.name);
  if (fromName) return fromName;
  const fromCode = slug(project && project.code);
  if (fromCode) return fromCode;
  return `project-${String((project && project.id) || crypto.randomUUID()).slice(0, 8)}`;
}

/* Claim a folder name for a project, once.
 *
 * The UNIQUE key on projects.server_folder is what makes this safe under two
 * simultaneous requests: the loser of the race gets a duplicate-key error and
 * tries the next name, rather than two projects quietly sharing a folder and
 * with it each other's files. */
async function folderFor(db, project) {
  if (!project || !project.id) return { ok: false, reason: 'No project.' };
  if (project.server_folder) return { ok: true, folder: project.server_folder, created: false };
  const { rows } = await db.query('SELECT server_folder FROM projects WHERE id = $1', [project.id]);
  if (rows.length && rows[0].server_folder) return { ok: true, folder: rows[0].server_folder, created: false };

  const base = derive(project);
  for (let n = 1; n <= 50; n += 1) {
    const candidate = n === 1 ? base : `${base}-${n}`;
    try {
      const { result } = await db.query(
        'UPDATE projects SET server_folder = $1 WHERE id = $2 AND server_folder IS NULL',
        [candidate, project.id]
      );
      if (result && Number(result.affectedRows) === 0) {
        // Somebody else set it between the read and the write; use theirs.
        const { rows: now } = await db.query('SELECT server_folder FROM projects WHERE id = $1', [project.id]);
        if (now.length && now[0].server_folder) return { ok: true, folder: now[0].server_folder, created: false };
      } else {
        return { ok: true, folder: candidate, created: true };
      }
    } catch (err) {
      if (err && (err.code === 'ER_DUP_ENTRY' || err.errno === 1062)) continue;   // taken by another project
      throw err;
    }
  }
  return { ok: false, reason: `Could not find a free folder name for "${project.name}".` };
}

/* THE PREFIXES THIS PERSON MAY REACH.
 *
 * Built from visibleProjects() — the one function in this application that
 * answers "which projects is this person allowed to be aware of" — so the
 * Server tab inherits every scoping rule the rest of the app has, including the
 * Acting Team Lead rule added in Prompt 50, with nothing to keep in step.
 */
async function allowedPrefixes(db, user) {
  if (permissions.holds(user, 'server.browse_all')) {
    return { all: true, prefixes: [''], projects: [], shared: serverSettings.current().sharedFolders };
  }
  const projects = await permissions.visibleProjects(user);
  const prefixes = [];
  const mapped = [];
  for (const project of projects) {
    // Only projects that ALREADY have a folder, plus a lazily claimed one the
    // first time this person looks: claiming here is what makes a brand-new
    // project usable without an admin visiting Settings first.
    const got = await folderFor(db, project);
    if (!got.ok) continue;
    prefixes.push(got.folder);
    mapped.push({ projectId: project.id, name: project.name, code: project.code || null, folder: got.folder });
  }
  const shared = serverSettings.current().sharedFolders;
  for (const name of shared) if (!prefixes.includes(name)) prefixes.push(name);
  return { all: false, prefixes, projects: mapped, shared };
}

/* Is this path inside any prefix this person holds? Segment-wise and
   case-insensitive. src/server-paths.js says why that rule lives on this side
   of the wall rather than being required out of the gateway package, and a test
   pins the two implementations against each other. */
function mayReach(prefixes, relative) {
  const want = String(relative === undefined || relative === null ? '' : relative);
  return (prefixes || []).some((p) => paths.within(want, p));
}

/* What the tab shows at the top. Not a listing of the root — a non-admin may
   not read the root at all — but the set of entry points they hold, which is
   the one screen in this feature that Forge answers from its own database
   rather than from the share. It names folders; it does not say what is in
   them. */
async function roots(db, user) {
  const { all, prefixes, projects, shared } = await allowedPrefixes(db, user);
  if (all) return { all: true, entries: [], shared };
  return {
    all: false,
    entries: [
      ...projects.map((p) => ({ name: p.folder, type: 'folder', kind: 'project', projectId: p.projectId, label: p.name, code: p.code })),
      ...shared.map((name) => ({ name, type: 'folder', kind: 'shared', label: name })),
    ],
    shared,
  };
}

/* The editable mapping table for Settings → Server. Every project, with the
   folder it holds or the name it would take. */
async function mapping(db) {
  const { rows } = await db.query(
    `SELECT p.id, p.\`name\`, p.\`code\`, p.server_folder, p.is_active, c.\`name\` AS client_name
       FROM projects p
       LEFT JOIN clients c ON c.id = p.client_id
      ORDER BY p.is_active DESC, c.\`name\`, p.\`name\``
  );
  return rows.map((r) => ({
    projectId: r.id,
    name: r.name,
    code: r.code || null,
    client: r.client_name || null,
    active: Boolean(Number(r.is_active)),
    folder: r.server_folder || null,
    wouldBe: r.server_folder ? null : derive({ id: r.id, name: r.name, code: r.code }),
  }));
}

async function setMapping(db, projectId, folder) {
  const name = String(folder === undefined || folder === null ? '' : folder).trim();
  if (!name) {
    /* Clearing is allowed and means "this project has no folder yet": the next
       person to look claims one. It does not touch anything on the share. */
    await db.query('UPDATE projects SET server_folder = NULL WHERE id = $1', [projectId]);
    return { ok: true, folder: null };
  }
  const clean = paths.cleanName(name);
  if (!clean.ok) return { ok: false, status: 400, error: clean.reason };
  try {
    const { result } = await db.query('UPDATE projects SET server_folder = $1 WHERE id = $2', [clean.value, projectId]);
    if (!result || Number(result.affectedRows) === 0) {
      const { rows } = await db.query('SELECT id FROM projects WHERE id = $1', [projectId]);
      if (!rows.length) return { ok: false, status: 404, error: 'No such project.' };
    }
  } catch (err) {
    if (err && (err.code === 'ER_DUP_ENTRY' || err.errno === 1062)) {
      return { ok: false, status: 409, error: `Another project already uses the folder "${clean.value}".` };
    }
    throw err;
  }
  return { ok: true, folder: clean.value };
}

module.exports = { slug, derive, folderFor, allowedPrefixes, mayReach, roots, mapping, setMapping };
